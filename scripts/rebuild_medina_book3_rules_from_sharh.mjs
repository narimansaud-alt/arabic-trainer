function termClass(ar) {
  const key = compactArabic(ar);
  if (/رفع|مرفوع|ضمة/u.test(key)) return 'rule-term-raf';
  if (/نصب|منصوب|فتحة|تمييز|حال/u.test(key)) return 'rule-term-nasb';
  if (/جر|مجرور|كسرة|مضاف/u.test(key)) return 'rule-term-jarr';
  if (/جزم|مجزوم|سكون/u.test(key)) return 'rule-term-jazm';
  if (/فعل|ماضي|مضارع|امر|مجهول|فاعل|مفعول|افعال|اعطي|اصبح|اوشك/u.test(key)) return 'rule-term-verb';
  if (/مبتدا|اسم|ضمير|معرفة|نكرة|مثنى|جمع|نعت|توكيد|عطف|بدل|تابع|جملة|مصدر/u.test(key)) return 'rule-term-structure';
  if (/حرف|لام|واو|لو|حتى|اذا|لم|لما|لا|من|كم|ما|لعل/u.test(key)) return 'rule-term-particle';
  if (/خبر/u.test(key)) return 'rule-term-predicate';
  return 'rule-term-default';
}

function findKnownTerms(ar, source) {
  const joined = `${ar}\n${source}`;
  const found = [];
  for (const [term, meaning] of TERM_MEANINGS.entries()) {
    if (joined.includes(term) || compactArabic(joined).includes(compactArabic(term))) {
      found.push([term, meaning]);
    }
  }
  const titleTerm = [ar, `${ar} — ${sourceTitleMeaning(ar)}`];
  const all = [titleTerm, ...found];
  const seen = new Set();
  return all.filter(([term]) => {
    const key = compactArabic(term);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  }).slice(0, 12);
}

function sourceTitleMeaning(ar) {
  for (const [term, meaning] of TERM_MEANINGS.entries()) {
    if (compactArabic(term) === compactArabic(ar)) return meaning;
  }
  return 'название правила; русский смысл указан в заголовке карточки';
}

function sourceLines(lines, start, end) {
  const section = lines
    .slice(start, end)
    .map((line) => line.trim())
    .filter((line) => line && !/^\(+\s*\(+\s*\(+/.test(line));
  if (!section.length) {
    throw new Error(`Empty source range ${start}-${end}. Check line splitting before building rules.`);
  }
  return section;
}

function sourceHtml(lines) {
  const clean = lines.filter((line) => line !== '---------' && line !== 'الأمثلة' && line !== 'الإعراب');
  const html = clean.map((line) => `<div class="rule-source-line">${esc(line)}</div>`).join('');
  return `<div class="rule-source-ar" dir="rtl" lang="ar">${html}</div>`;
}

function exampleLines(lines) {
  return lines
    .filter((line) => /[.؟!:]|نحو|الأمثلة|الإعراب/u.test(line))
    .filter((line) => /[\u0600-\u06FF]/u.test(line))
    .slice(0, 5);
}

function meaningGrid(topic, source) {
  const terms = findKnownTerms(topic.ar, source);
  return `<div class="rule-meaning-grid">${terms.map(([ar, ru]) =>
    `<div class="rule-meaning-card ${termClass(ar)}"><span class="rule-term-ar" dir="rtl" lang="ar">${esc(ar)}</span><span class="rule-term-ru">${esc(ru)}</span></div>`
  ).join('')}</div>`;
}

function examplesCard(lines) {
  const examples = exampleLines(lines);
  if (!examples.length) return '';
  return `<div class="rule-study-card"><span class="rule-card-kicker">Примеры и разборы из шарха</span><div class="rule-example-list">${examples.map((line) =>
    `<div class="rule-example-card ${termClass(line)}"><span class="rule-example-ar" dir="rtl" lang="ar">${esc(line)}</span><span class="rule-example-ru">Пример/разбор сохранён из арабского шарха.</span></div>`
  ).join('')}</div></div>`;
}

function buildContent(topic, lines) {
  const sectionLines = sourceLines(lines, topic.start, topic.end);
  const source = sectionLines.join('\n');
  const titleCard = `<div class="rule-study-card"><span class="rule-card-kicker">Название и смысл</span><span class="rule-main-ar" dir="rtl" lang="ar">${esc(topic.ar)}</span><p class="rule-study-text">${esc(topic.ru)}. ${esc(topic.summary)}</p></div>`;
  const meaningCard = `<div class="rule-study-card"><span class="rule-card-kicker">Арабские слова → русский смысл</span>${meaningGrid(topic, source)}</div>`;
  const stepsCard = `<div class="rule-study-card"><span class="rule-card-kicker">Как применять</span><ol>${GENERIC_STEPS.map((step) => `<li>${esc(step)}</li>`).join('')}</ol></div>`;
  const sourceCard = `<div class="rule-study-card rule-study-source"><span class="rule-card-kicker">Текст шарха по этой теме</span>${sourceHtml(sectionLines)}</div>`;
  const checkCard = `<div class="rule-check-card"><b>Проверка:</b> сверяйте роль слова, عامل и конечный признак. Если слово مبنيّ, говорите «في محل رفع/نصب/جر», а если معرب — «مرفوع/منصوب/مجرور/مجزوم».</div>`;
  return `<div class="rule-study">${titleCard}${meaningCard}${stepsCard}${examplesCard(sectionLines)}${sourceCard}${checkCard}</div>`;
}

