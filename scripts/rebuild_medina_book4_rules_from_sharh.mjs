function termClass(ar) {
  const key = compactArabic(ar);
  if (/رفع|مرفوع|ضمة/.test(key)) return 'rule-term-raf';
  if (/نصب|منصوب|فتحة|تمييز|حال|مستثنى|مفعول/.test(key)) return 'rule-term-nasb';
  if (/جر|مجرور|كسرة|مضاف/.test(key)) return 'rule-term-jarr';
  if (/جزم|مجزوم|سكون/.test(key)) return 'rule-term-jazm';
  if (/فعل|ماض|مضارع|امر|فاعل|مفعول|باب|نونالتوكيد/.test(key)) return 'rule-term-verb';
  if (/اسم|ضمير|مصدر|بدل|نعت|تمييز|حال|استثناء|ممنوعمنالصرف/.test(key)) return 'rule-term-structure';
  if (/حرف|لام|قد|لا|لولا|لوما|انما|الا|ما|من|بل|لكن|حتى|اذا|عسى/.test(key)) return 'rule-term-particle';
  if (/خبر/.test(key)) return 'rule-term-predicate';
  return 'rule-term-default';
}

function titleMeaning(ar) {
  for (const [term, meaning] of TERM_MEANINGS.entries()) {
    if (compactArabic(term) === compactArabic(ar)) return meaning;
  }
  return 'название правила; русский смысл указан в заголовке карточки';
}

function knownTerms(topic, source) {
  const joined = `${topic.ar}\n${source}`;
  const compact = compactArabic(joined);
  const terms = [[topic.ar, `${topic.ar} — ${titleMeaning(topic.ar)}`]];
  for (const [term, meaning] of TERM_MEANINGS.entries()) {
    if (joined.includes(term) || compact.includes(compactArabic(term))) terms.push([term, meaning]);
  }
  const seen = new Set();
  return terms.filter(([term]) => {
    const key = compactArabic(term);
    if (!key || seen.has(key)) return false;
    seen.add(key);
    return true;
  }).slice(0, 14);
}

function sourceLines(lines, start, end) {
  const section = lines
    .slice(start, end)
    .map((line) => line.trim())
    .filter((line) => line && !/^\(+\s*\(+\s*\(+/.test(line));
  if (!section.length) throw new Error(`Empty source range ${start}-${end}`);
  return section;
}

function sourceHtml(lines) {
  return `<div class="rule-source-ar" dir="rtl" lang="ar">${lines
    .filter((line) => line !== '---------')
    .map((line) => `<div class="rule-source-line">${esc(line)}</div>`)
    .join('')}</div>`;
}

function exampleLines(lines) {
  return lines
    .filter((line) => /نحو|الإعراب|قال|[:.؟!]|[|]/u.test(line))
    .filter((line) => /[\u0600-\u06FF]/u.test(line))
    .slice(0, 7);
}

