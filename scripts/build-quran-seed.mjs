import fs from 'node:fs';
import assert from 'node:assert/strict';
const data = JSON.parse(fs.readFileSync('data/quran-vocabulary.json', 'utf8'));
assert.equal(data.words.length, 1000);
const quote = value => "'" + String(value).replaceAll("'", "''") + "'";
const course = quote(data.course);
const rows = data.words.map(word => {
  const metadata = {
    rank:word.rank, frequency:word.frequency, sourceRank:word.sourceRank,
    kind:word.kind, inputForm:word.sourceRank===250?'present':word.sourceRank===1000?'imperative':word.kind==='verb'?'past':'lemma',
    sourceRecords:word.sourceRecords, note:word.note, example:word.example
  };
  return '(' + [course,quote(word.block),quote(word.ar),quote(word.ru),word.rank,"'single'",quote(JSON.stringify(metadata))+'::jsonb'].join(',') + ')';
});
const sql = [
 '-- Generated by scripts/build-quran-seed.mjs. Source: Quranic Arabic Corpus, © 2011 Kais Dukes.',
 '-- See docs/QURAN_VOCABULARY.md for source conditions, method and corrections.',
 'begin;',
 'alter table public.words add column if not exists vocabulary_meta jsonb;',
 "comment on column public.words.vocabulary_meta is 'Optional lexical frequency, source references and answer-form metadata; no user data.';",
 'create unique index if not exists words_quran_frequency_rank on public.words',
 "  (course_name, ((vocabulary_meta->>'rank')::integer)) where course_name = " + course + ';',
 'insert into public.words (course_name, lesson_number, word_ar, word_ru, dictionary_row, dictionary_form, vocabulary_meta) values',
 rows.join(',\n'),
 "on conflict (course_name, ((vocabulary_meta->>'rank')::integer)) where course_name = " + course,
 'do update set lesson_number=excluded.lesson_number, word_ar=excluded.word_ar, word_ru=excluded.word_ru,',
 ' dictionary_row=excluded.dictionary_row, dictionary_form=excluded.dictionary_form, vocabulary_meta=excluded.vocabulary_meta;',
 'do $$ begin',
 ' if (select count(*) from public.words where course_name = '+course+') <> 1000 then',
 "  raise exception 'Quran vocabulary must contain exactly 1000 cards';",
 ' end if;',
 'end $$;',
 "notify pgrst, 'reload schema';",
 'commit;',''
].join('\n');
fs.writeFileSync('supabase/migrations/20260902090100_add_quran_frequency_words.sql',sql);
console.log('Generated id-preserving seed for 1000 words.');
