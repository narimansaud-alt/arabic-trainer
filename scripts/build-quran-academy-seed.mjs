import fs from 'node:fs';
import assert from 'node:assert/strict';
const data = JSON.parse(fs.readFileSync('data/quran-academy-vocabulary.json', 'utf8'));
assert.equal(data.revision, 'uqa-85-2020-ru-v1');
assert.ok(data.words.length > 700 && data.words.length < 1000);
const quote = value => "'" + String(value).replaceAll("'", "''") + "'";
const course = quote(data.course);
const values = data.words.map(w => '(' + [quote(w.ar), quote(w.ru), quote(w.block), w.rank,
  quote(JSON.stringify({dataset: data.revision, rank: w.rank, kind: w.kind, inputForm: w.inputForm,
    sourcePages: [...new Set(w.sourceRows.map(r => r.page))], source: data.source.url,
    present: [...new Set(w.verbForms.map(f => f.present))].join('، ')})) + '::jsonb'].join(',') + ')');
const sql = `-- Generated by scripts/build-quran-academy-seed.mjs; see docs/QURAN_VOCABULARY.md.
-- Replace only this reference collection. Never update/delete student tables.
begin;
lock table public.words in share row exclusive mode;
create temporary table quran_academy_source (
  ar text primary key, ru text not null, lesson text not null, rank integer unique not null, meta jsonb not null
) on commit drop;
insert into quran_academy_source values
${values.join(',\n')};
create temporary table quran_academy_untouched on commit drop as
  select * from public.words where course_name <> ${course};
create temporary table quran_academy_identity on commit drop as
  select w.id,w.word_ar from public.words w join quran_academy_source s on s.ar=w.word_ar where w.course_name=${course};
-- Free the old rank-based unique index before assigning the new source order.
update public.words set vocabulary_meta=null where course_name=${course};
delete from public.words w where w.course_name=${course}
  and not exists(select 1 from quran_academy_source s where s.ar=w.word_ar);
update public.words w set word_ru=s.ru,lesson_number=s.lesson,dictionary_row=s.rank,
  dictionary_form='single',vocabulary_meta=s.meta
from quran_academy_source s where w.course_name=${course} and w.word_ar=s.ar;
insert into public.words(course_name,lesson_number,word_ar,word_ru,dictionary_row,dictionary_form,vocabulary_meta)
select ${course},s.lesson,s.ar,s.ru,s.rank,'single',s.meta from quran_academy_source s
where not exists(select 1 from public.words w where w.course_name=${course} and w.word_ar=s.ar)
order by s.rank;
do $checks$ begin
  if (select count(*) from public.words where course_name=${course}) <> ${data.words.length}
    then raise exception 'Academy collection count mismatch'; end if;
  if exists((select * from public.words where course_name <> ${course} except all select * from quran_academy_untouched)
    union all (select * from quran_academy_untouched except all select * from public.words where course_name <> ${course}))
    then raise exception 'Unrelated words changed'; end if;
  if exists(select 1 from quran_academy_identity i left join public.words w on w.id=i.id
    where w.word_ar is distinct from i.word_ar)
    then raise exception 'Shared Arabic identity changed'; end if;
  if exists(select 1 from quran_academy_source s left join public.words w on w.course_name=${course} and w.word_ar=s.ar
    where w.word_ru is distinct from s.ru or w.lesson_number is distinct from s.lesson or w.vocabulary_meta is distinct from s.meta)
    then raise exception 'Academy source reverse comparison failed'; end if;
end $checks$;
notify pgrst, 'reload schema';
commit;
`;
fs.writeFileSync('supabase/migrations/20260903003000_replace_quran_vocabulary_with_academy.sql', sql);
console.log('Generated scoped, identity-preserving Academy migration: ' + data.words.length + ' cards.');
