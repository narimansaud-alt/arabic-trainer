declare
  actual_records integer;
  actual_rows integer;
  actual_single integer;
  actual_singular integer;
  actual_plural integer;
  paired_rows integer;
  plural_only_rows integer;
begin
  select
    count(*),
    count(distinct dictionary_row),
    count(*) filter (where dictionary_form = 'single'),
    count(*) filter (where dictionary_form = 'singular'),
    count(*) filter (where dictionary_form = 'plural')
  into
    actual_records,
    actual_rows,
    actual_single,
    actual_singular,
    actual_plural
  from public.words
  where course_name = 'Мединский курс (Том 4)'
    and lesson_number = '2';

  select count(*)
  into paired_rows
  from (
    select dictionary_row
    from public.words
    where course_name = 'Мединский курс (Том 4)'
      and lesson_number = '2'
    group by dictionary_row
    having count(*) filter (where dictionary_form = 'singular') = 1
       and count(*) filter (where dictionary_form = 'plural') = 1
  ) pairs;

  select count(*)
  into plural_only_rows
  from (
    select dictionary_row
    from public.words
    where course_name = 'Мединский курс (Том 4)'
      and lesson_number = '2'
    group by dictionary_row
    having count(*) = 1
       and count(*) filter (where dictionary_form = 'plural') = 1
  ) plural_only;

  if actual_records <> 77
    or actual_rows <> 64
    or actual_single <> 50
    or actual_singular <> 13
    or actual_plural <> 14
    or paired_rows <> 13
    or plural_only_rows <> 1 then
    raise exception
      'Book 4 lesson 2 dictionary verification failed: % records, % rows, % single, % singular, % plural, % pairs, % plural-only',
      actual_records,
      actual_rows,
      actual_single,
      actual_singular,
      actual_plural,
      paired_rows,
      plural_only_rows;
  end if;
end
$$;

