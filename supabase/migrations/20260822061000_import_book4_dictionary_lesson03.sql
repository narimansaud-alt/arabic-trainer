declare
  actual_records integer;
  actual_rows integer;
  actual_single integer;
  actual_singular integer;
  actual_plural integer;
  paired_rows integer;
  first_row integer;
  last_row integer;
begin
  select
    count(*),
    count(distinct dictionary_row),
    count(*) filter (where dictionary_form = 'single'),
    count(*) filter (where dictionary_form = 'singular'),
    count(*) filter (where dictionary_form = 'plural'),
    min(dictionary_row),
    max(dictionary_row)
  into
    actual_records,
    actual_rows,
    actual_single,
    actual_singular,
    actual_plural,
    first_row,
    last_row
  from public.words
  where course_name = 'Мединский курс (Том 4)'
    and lesson_number = '3';

  select count(*)
  into paired_rows
  from (
    select dictionary_row
    from public.words
    where course_name = 'Мединский курс (Том 4)'
      and lesson_number = '3'
    group by dictionary_row
    having count(*) filter (where dictionary_form = 'singular') = 1
       and count(*) filter (where dictionary_form = 'plural') = 1
  ) pairs;

  if actual_records <> 81
    or actual_rows <> 65
    or actual_single <> 49
    or actual_singular <> 16
    or actual_plural <> 16
    or paired_rows <> 16
    or first_row <> 1
    or last_row <> 65 then
    raise exception
      'Book 4 lesson 3 dictionary verification failed: % records, % rows, % single, % singular, % plural, % pairs, rows %-%',
      actual_records,
      actual_rows,
      actual_single,
      actual_singular,
      actual_plural,
      paired_rows,
      first_row,
      last_row;
  end if;
end
$$;

