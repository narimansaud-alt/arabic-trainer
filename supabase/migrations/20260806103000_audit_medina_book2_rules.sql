<b>Суть правила.</b> Названия дней недели являются именами времени. В зависимости от роли они могут быть обстоятельством времени в насбе или частью идафы, например يَوْمُ السَّبْتِ — «субботний день/суббота».
<div class="rule-steps"><b>Как применять.</b><ol><li>Выберите название дня: السَّبْتُ، الْأَحَدُ، الِاثْنَيْنِ и другие.</li><li>Поставьте день в нужный падеж по его роли.</li><li>В конструкции с يَوْمِ второе слово ставится в родительном падеже как مضاف إليه.</li></ol></div>
<br><b>Примеры.</b><ul>
<li><b dir="rtl" lang="ar">سَأَذْهَبُ يَوْمَ السَّبْتِ.</b> — Я пойду в субботу.</li>
<li><b dir="rtl" lang="ar">يَدْرُسُ أَخِي يَوْمَ الِاثْنَيْنِ.</b> — Мой брат учится в понедельник.</li>
<li><b dir="rtl" lang="ar">يَوْمُ الْجُمُعَةِ يَوْمٌ مُبَارَكٌ.</b> — Пятница — благословенный день.</li>
</ul>
<div class="rule-example-analysis"><b>Полный разбор إعراب.</b> В <b dir="rtl" lang="ar">سَأَذْهَبُ يَوْمَ السَّبْتِ</b> <b>سَأَذْهَبُ</b> — المضارع с приставкой будущего سَـ, <b>يَوْمَ</b> — ظرف زمان в насбе и مضاف, <b>السَّبْتِ</b> — مضاف إليه в джарре.</div>
