<div class="rule-steps"><b>Как применять.</b><ol><li>Назовите сезон с определённым артиклем.</li><li>Определите его синтаксическую роль и падеж.</li><li>Для значения «летом/зимой» используйте ظرف زمان, например فِي الصَّيْفِ или صَيْفًا.</li></ol></div>
<br><b>Примеры.</b><ul>
<li><b dir="rtl" lang="ar">أُحِبُّ الرَّبِيعَ.</b> — Я люблю весну.</li>
