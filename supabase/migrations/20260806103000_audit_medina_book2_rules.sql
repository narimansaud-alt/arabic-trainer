<li><b dir="rtl" lang="ar">قَالَ الْمُدَرِّسُ: إِنَّ الدَّرْسَ سَهْلٌ.</b> — Учитель сказал: «Урок лёгкий».</li>
<li><b dir="rtl" lang="ar">عَلِمْتُ أَنَّ الدَّرْسَ سَهْلٌ.</b> — Я узнал, что урок лёгкий.</li>
<li><b dir="rtl" lang="ar">إِنَّ الطَّالِبَ مُجْتَهِدٌ، وَأَظُنُّ أَنَّهُ نَاجِحٌ.</b> — Студент прилежный, и я думаю, что он преуспеет.</li>
</ul>
<div class="rule-example-analysis"><b>Полный разбор إعراب.</b> В <b dir="rtl" lang="ar">عَلِمْتُ أَنَّ الدَّرْسَ سَهْلٌ</b> <b>أَنَّ الدَّرْسَ سَهْلٌ</b> — مصدر مؤول в роли مفعول به после <b>عَلِمْتُ</b>. <b>الدَّرْسَ</b> — اسم أَنَّ в насбе, <b>سَهْلٌ</b> — خبر أَنَّ в рафʿе.</div>
